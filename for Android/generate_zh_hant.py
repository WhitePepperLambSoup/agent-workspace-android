"""Regenerate web_companion/static/i18n-zh-hant.js, the Traditional Chinese (Taiwan) UI catalog.

Every Chinese UI string of web_companion/static/i18n.js (the English catalog keys and the
Chinese server error messages) is converted with OpenCC s2twp. Run it after adding UI text:

    pip install opencc-python-reimplemented
    python generate_zh_hant.py
"""

import json
import re
from pathlib import Path

STATIC = Path(__file__).resolve().parent / "web_companion" / "static"
# Same ranges as the i18n tests: ideographs, CJK punctuation and full-width forms.
CJK = re.compile(r"[一-鿿　-〿＀-￯]")
TOKEN = re.compile(r'"(?:[^"\\]|\\.)*"(\s*:)?|//[^\n]*')


def _strings(source: str, opening: str, keys: bool) -> list[str]:
    """The keys (or the values) of one object literal of i18n.js; several entries may share a line."""
    start = source.index(opening) + len(opening)
    section = source[start:source.index("\n  };", start)]
    found = []
    for match in TOKEN.finditer(section):
        if match.group(0).startswith("//"):
            continue
        if bool(match.group(1)) == keys:
            found.append(json.loads(match.group(0)[: len(match.group(0)) - len(match.group(1) or "")]))
    return found


def ui_texts() -> list[str]:
    """Every Chinese UI string: the English catalog keys and the Chinese server error messages."""
    source = (STATIC / "i18n.js").read_text(encoding="utf-8")
    texts = _strings(source, "  const en = {", keys=True) + _strings(source, "  const serverErrorsZh = {", keys=False)
    return [text for text in dict.fromkeys(texts) if CJK.search(text)]


def main() -> None:
    from opencc import OpenCC  # Only this script needs it; generate_ja_ko.py reuses the parser above.

    texts = ui_texts()
    convert = OpenCC("s2twp").convert
    catalog = {text: convert(text) for text in texts}
    body = ",\n".join(
        f"    {json.dumps(key, ensure_ascii=False)}: {json.dumps(value, ensure_ascii=False)}"
        for key, value in catalog.items()
    )
    # Bytes, so the file keeps LF line endings on Windows too.
    (STATIC / "i18n-zh-hant.js").write_bytes((
        "/* Traditional Chinese (Taiwan) for the web UI: every Chinese string of i18n.js converted with OpenCC\n"
        "   (s2twp). Generated by generate_zh_hant.py; loads before i18n.js, which uses it for zh-Hant. */\n"
        "window.MobileI18nHant = {\n" + body + "\n};\n"
    ).encode("utf-8"))
    print(len(catalog), "strings")


if __name__ == "__main__":
    main()
